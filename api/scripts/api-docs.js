/**
 * Writes docs/api/README.md from the routes' doc comments (`METHOD /path` then a description), so
 * the reference follows the code. Run it after changing a route.
 *
 * Usage (repo root): docker run --rm -v "$PWD":/w -w /w node:22-alpine node api/scripts/api-docs.js
 */
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROUTES = path.join(import.meta.dirname, '../route');
const OUTPUT = path.join(import.meta.dirname, '../../docs/api/README.md');

/** Who may call a route, from its `auth()` options. */
const ACCESS = {
    'auth()': 'signed in',
    'auth({ optional: true })': 'anyone (session optional)',
    'auth({ admin: true })': 'administrators',
};

/**
 * @param {string} text
 * @returns {string|null} The access of the first `auth(...)` call in the text.
 */
function accessOf(text) {
    const match = text.match(/auth\((\{[^}]*\})?\)/);
    return match ? ACCESS[match[0]] ?? match[0] : null;
}

/**
 * @param {string} source A route file.
 * @returns {Array<{ method: string, path: string, access: string, description: string }>}
 */
function routesOf(source) {
    const fileAccess = accessOf(source.match(/^router\.use\(.*$/m)?.[0] ?? '') ?? 'anyone';
    const routes = [];
    for (const [, comment, call] of source.matchAll(/\/\*\*\n((?: \*.*\n)+?) \*\/\nrouter\.(?:get|post|put|delete|patch)\(([^\n]*)/g)) {
        const lines = comment.split('\n').map(line => line.replace(/^ \* ?/, '')).filter(Boolean);
        const [method, ...rest] = lines.shift().split(' ');
        routes.push({
            method,
            path: rest.join(' '),
            access: accessOf(call) ?? fileAccess,
            description: lines.join(' ').replace(/\|/g, '\\|'),
        });
    }
    return routes;
}

const files = (await readdir(ROUTES)).filter(file => file.endsWith('.js')).sort();
const sections = [];
for (const file of files) {
    const routes = routesOf(await readFile(path.join(ROUTES, file), 'utf8'));
    if (!routes.length) continue;
    const rows = routes.map(route => `| \`${route.method}\` | \`${route.path}\` | ${route.access} | ${route.description} |`);
    sections.push(`## ${file.replace(/\.js$/, '')}\n\nFrom \`api/route/${file}\`.\n\n| Method | Path | Access | Description |\n| --- | --- | --- | --- |\n${rows.join('\n')}\n`);
}

const intro = `# gladCode API reference

Generated by \`api/scripts/api-docs.js\` from the route comments in \`api/route/\`; do not edit by
hand. Run \`docker run --rm -v "$PWD":/w -w /w node:22-alpine node api/scripts/api-docs.js\` after
changing a route.

- **Base URL**: \`API_URL:API_PORT\` (production \`https://api.gladcode.dev\`). Bodies and answers are
  JSON with camelCase fields; dates are \`YYYY-MM-DD HH:MM:SS\` strings in the server's time zone.
- **Session**: \`POST /auth/google\` sets the \`app_session\` HttpOnly cookie (a signed JWT); browsers
  send it with \`credentials: 'include'\`. Administrators are the accounts listed in \`ADMIN_EMAILS\`.
- **Origin**: only \`WEB_URL:WEB_PORT\` may call the API from a browser (CORS), and requests that
  change something with the cookie must come from that origin.
- **Errors**: \`{ error: true, status, type, code, message, data? }\`. \`code\` is stable
  (\`NOT_SIGNED_IN\`, \`ADMIN_ONLY\`, \`INVALID_<FIELD>\`, \`TOURNAMENT_STARTED\`, ...) and is what clients
  should branch on; \`data\` carries details for some codes.
- **Health**: \`GET /health\` (process alive) and \`GET /ready\` (database reachable).
`;

await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, `${intro}\n${sections.join('\n')}`);
console.log(`${sections.length} areas written to ${path.relative(process.cwd(), OUTPUT)}`);
